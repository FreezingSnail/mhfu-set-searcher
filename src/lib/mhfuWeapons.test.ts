import assert from "node:assert/strict";
import { test } from "node:test";
import weapons from "../data/weapons.json" with { type: "json" };
import type { Weapon } from "./types.ts";

const rankForRarity = (rarity: number): Weapon["rank"] =>
  rarity <= 4 ? "lr" : rarity <= 8 ? "hr" : "gr";

test("MHFU weapon ranks follow the game's rarity bands", () => {
  for (const weapon of weapons as Weapon[]) {
    assert.equal(weapon.rank, rankForRarity(weapon.rarity), weapon.name);
  }
});

test("Ashen Lao weapons generated by high-rank quests are high rank", () => {
  for (const name of ["Empr Lao-Shan Cannon", "Suprm Lao-Shan Cannon"]) {
    const weapon = (weapons as Weapon[]).find((entry) => entry.name === name);
    assert.ok(weapon, `${name} missing from weapon data`);
    assert.equal(weapon.rank, "hr", name);
  }
});
